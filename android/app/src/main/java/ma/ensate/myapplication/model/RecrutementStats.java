package ma.ensate.myapplication.model;

public class RecrutementStats {
    private int postesOuverts;
    private long totalCandidatures;
    private long entretiensPlanifies;

    public int getPostesOuverts() { return postesOuverts; }
    public void setPostesOuverts(int postesOuverts) { this.postesOuverts = postesOuverts; }
    public long getTotalCandidatures() { return totalCandidatures; }
    public void setTotalCandidatures(long totalCandidatures) { this.totalCandidatures = totalCandidatures; }
    public long getEntretiensPlanifies() { return entretiensPlanifies; }
    public void setEntretiensPlanifies(long entretiensPlanifies) { this.entretiensPlanifies = entretiensPlanifies; }
}
